import { LETTERING_CHARACTERS, LETTERING_STYLE, PILOT_HEADINGS } from './source-font.mjs'

function sortByCodePoint(left, right) {
  return left.codePointAt(0) - right.codePointAt(0)
}

function json(value) {
  return JSON.stringify(value)
}

export function createGeneratedSource(font, transformedGlyphs) {
  const characters = [
    ...new Set([...LETTERING_CHARACTERS, ...PILOT_HEADINGS.flatMap((heading) => [...heading])]),
  ]
    .filter((character) => character !== ' ')
    .sort(sortByCodePoint)
  const glyphEntries = characters.map((character) => {
    const glyph = transformedGlyphs.get(character)
    if (!glyph) throw new Error(`No transformed geometry for ${JSON.stringify(character)}`)
    return [
      `  ${json(character)}: {`,
      `    bodyPath: ${json(glyph.bodyPath)},`,
      `    outlinePath: ${json(glyph.outlinePath)},`,
      `    advance: ${glyph.advance},`,
      `    bounds: { xMin: ${glyph.bounds.xMin}, yMin: ${glyph.bounds.yMin}, xMax: ${glyph.bounds.xMax}, yMax: ${glyph.bounds.yMax} },`,
      '  },',
    ].join('\n')
  })

  const kerningPairs = []
  for (const left of characters) {
    for (const right of characters) {
      const value = font.getKerningValue(font.charToGlyph(left), font.charToGlyph(right))
      if (value !== 0) kerningPairs.push([`${left.codePointAt(0)},${right.codePointAt(0)}`, value])
    }
  }

  const uniqueKerningPairs = [...new Map(kerningPairs).entries()].sort(([left], [right]) => {
    const [leftA, leftB] = left.split(',').map(Number)
    const [rightA, rightB] = right.split(',').map(Number)
    return leftA - rightA || leftB - rightB
  })
  const spaceGlyph = font.charToGlyph(' ')
  const metrics = {
    unitsPerEm: font.unitsPerEm,
    ascender: font.ascender,
    descender: font.descender,
    spaceAdvance: spaceGlyph.advanceWidth,
    tracking: LETTERING_STYLE.tracking,
    spaceTracking: LETTERING_STYLE.spaceTracking,
    shadowX: LETTERING_STYLE.shadowX,
    shadowY: LETTERING_STYLE.shadowY,
  }

  return [
    '/* Generated by scripts/generate-lettering.mjs. Do not edit by hand. */',
    'export interface GeneratedGlyph {',
    '  bodyPath: string',
    '  outlinePath: string',
    '  advance: number',
    '  bounds: { xMin: number; yMin: number; xMax: number; yMax: number }',
    '}',
    '',
    `export const LETTERING_METRICS = ${json(metrics)} as const`,
    '',
    'export const LETTERING_GLYPHS: Readonly<Record<string, GeneratedGlyph>> = {',
    glyphEntries.join('\n'),
    '}',
    '',
    `export const LETTERING_KERNING: Readonly<Record<string, number>> = ${json(Object.fromEntries(uniqueKerningPairs))}`,
    '',
  ].join('\n')
}
